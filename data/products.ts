export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

export function getProductsByCategory(category: ProductCategory): Product[] {
  return products.filter((p) => p.category === category);
}

/**
 * Link beli final per produk:
 * kategori shopee → URL toko Shopee; premium → WhatsApp order.
 */
export function purchaseLink(product: Product): string {
  if (product.purchaseUrl) return product.purchaseUrl;
  if (product.category === 'shopee') return siteConfig.shopeeUrl;
  return siteConfig.whatsappUrl;
}
